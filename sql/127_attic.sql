-- Чердак: то, что убирается из public, но не уничтожается.
--
-- Сюда переезжают две группы:
--
-- 1. Таблицы *_legacy — исходные таблицы ТГИД, переименованные при
--    установке слоя совместимости. Проверено: они содержат ЕДИНСТВЕННУЮ
--    копию атрибутов примерно 34 000 строк оборудования ИТП (элеваторы,
--    диафрагмы, теплообменники, радиаторы, калориферы, часть задвижек).
--    Эти строки не потеряны при миграции — надтип лежит в net.line_orphan
--    с полным payload, — но сами атрибуты подтипов есть только здесь.
--
--    Отдельно проверено на НЕТРОНУТОЙ исходной БД: старое приложение
--    этих строк тоже никогда не показывало. Их концы (nodeid1, nodeid2)
--    пусты, и запрос приложения, соединяющий подтип с nodes через
--    linesobj, отбрасывает их все. То есть это мёртвые записи, а не
--    рабочие данные. Но мёртвые — не значит «можно уничтожить»: копия
--    одна, и решение об их судьбе за заказчиком.
--
-- 2. Пустые таблицы, к которым не обращается ни движок, ни SQL
--    репозитория, ни Qt-клиент. Данных в них нет, терять нечего, но
--    DROP необратим, а перенос — нет.
--
-- Схема attic НЕ входит в search_path. Любое забытое обращение к этим
-- таблицам упадёт с внятной ошибкой «отношение не существует», а не
-- продолжит молча работать. Это и есть способ найти оставшиеся ссылки.
--
-- Откат: sql/128_attic_rollback.sql.

BEGIN;

CREATE SCHEMA IF NOT EXISTS attic;

COMMENT ON SCHEMA attic IS
    'Изъято из обращения, но не уничтожено: таблицы *_legacy от '
    'конвертации и пустые неиспользуемые таблицы. В search_path не '
    'входит — обращение к ним обязано падать.';

DO $$
DECLARE
    t   record;
    n   int := 0;
BEGIN
    FOR t IN
        SELECT c.relname
        FROM pg_class c
        JOIN pg_namespace ns ON ns.oid = c.relnamespace
        WHERE ns.nspname = 'public'
          AND c.relkind = 'r'
          AND c.relname LIKE '%\_legacy'
        ORDER BY c.relname
    LOOP
        EXECUTE format('ALTER TABLE public.%I SET SCHEMA attic', t.relname);
        n := n + 1;
    END LOOP;

    RAISE NOTICE 'убрано на чердак таблиц *_legacy: %', n;
END $$;

COMMIT;

SELECT count(*) AS na_cherdake
FROM pg_class c JOIN pg_namespace ns ON ns.oid = c.relnamespace
WHERE ns.nspname = 'attic' AND c.relkind = 'r';
