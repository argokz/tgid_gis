-- Стабильный порядок строк для расчётного ядра.
--
-- Ядро строит граф в порядке поступления строк из выборки, поэтому
-- результат расчёта зависит от этого порядка. На исходной БД порядок
-- физический и потому одинаковый от прогона к прогону: два расчёта
-- подряд дают побитово совпадающий результат.
--
-- В схеме net таблицы крупнее и планировщик включает параллельное
-- сканирование, а оно отдаёт строки в произвольном порядке. Из-за этого
-- два прогона на одной и той же БД расходились на 451 ячейку ut_out.
--
-- ORDER BY в представлении эту задачу решает, но ценой сортировки всего
-- union при каждом обращении: выборка участков теплопровода переставала
-- укладываться в 10 минут. Поэтому порядок стабилизируется отключением
-- параллельного чтения для объектных таблиц.
--
-- Плата: крупные выборки по этим таблицам не используют несколько ядер.
-- Для расчёта это выгодный размен — он читает таблицы целиком один раз.

DO $$
DECLARE t text;
BEGIN
    FOR t IN
        SELECT c.relname
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'net' AND c.relkind = 'r'
          AND (c.relname LIKE 'extra_%'
               OR EXISTS (SELECT 1 FROM pg_attribute a
                          WHERE a.attrelid = c.oid AND a.attname = 'geom'
                            AND a.attnum > 0 AND NOT a.attisdropped))
    LOOP
        EXECUTE format('ALTER TABLE net.%I SET (parallel_workers = 0)', t);
    END LOOP;
END $$;

\echo 'Параллельное чтение объектных таблиц отключено — порядок строк стабилен'
