string getMime(string szFileName)
{
  string szContentType("text/html");
  int nPointPos = szFileName.rfind(".");
  if(nPointPos != string::npos)
  {
    string szFileExt = szFileName.substr(nPointPos + 1, szFileName.size());
    _strlwr((char*)szFileExt.c_str());
    map<string, string>::iterator it = MimeTypes.find(szFileExt);
    if (it != MimeTypes.end()) {
      szContentType = (*it).second;
    }
  }
  return szContentType;
}
