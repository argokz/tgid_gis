WITH SourceData AS (
    SELECT
        n.id                    AS [ID узла],
        n.externalNodeName      AS [Наименование],

        -- Требуемые нагрузки (из PT_OUT)
        ptOut.Qotz_treb         AS [Треб. отопл. (зав.), Гкал/ч],
        ptOut.Qotn_treb         AS [Треб. отопл. (незав.), Гкал/ч],
        ptOut.Qvent_treb        AS [Треб. вент., Гкал/ч],

        -- Фактические (полученные) нагрузки
        ptOut.Qotz              AS [Получ. отопл. (зав.), Гкал/ч],
        ptOut.Qotn              AS [Получ. отопл. (незав.), Гкал/ч],
        ptOut.dop12             AS [Получ. вент., Гкал/ч]

    FROM nodes n
        INNER JOIN generalizedConsumers gc ON gc.nodeID = n.id  -- только обобщённые потребители

        -- Последний расчёт по fileID
        OUTER APPLY (
            SELECT TOP 1 c.id AS last_calc_id
            FROM CALCULATION c
            WHERE c.fileID = n.fileID
            ORDER BY c.id DESC
        ) calc

        LEFT JOIN PT_OUT ptOut 
               ON ptOut.nodeID = n.id 
              AND ptOut.calculationID = calc.last_calc_id

    WHERE n.removed = 0
      AND n.fileID = $fileID$
      AND n.externalSignID = 1
      AND n.internalNodeID IS NULL
)
SELECT
    [ID узла],
    [Наименование],

    [Треб. отопл. (зав.), Гкал/ч],
    [Треб. отопл. (незав.), Гкал/ч],
    [Треб. вент., Гкал/ч],
    [Получ. отопл. (зав.), Гкал/ч],
    [Получ. отопл. (незав.), Гкал/ч],
    [Получ. вент., Гкал/ч],

    -- Теплообеспечение СО (отопление зависимое + независимое)
    ROUND(
        100.0 * (COALESCE([Получ. отопл. (зав.), Гкал/ч], 0) + COALESCE([Получ. отопл. (незав.), Гкал/ч], 0))
        / NULLIF(COALESCE([Треб. отопл. (зав.), Гкал/ч], 0) + COALESCE([Треб. отопл. (незав.), Гкал/ч], 0), 0),
        2
    ) AS [Теплообесп. СО, %],

    -- Теплообеспечение СВ (вентиляция)
    ROUND(
        100.0 * COALESCE([Получ. вент., Гкал/ч], 0) 
        / NULLIF(COALESCE([Треб. вент., Гкал/ч], 0), 0),
        2
    ) AS [Теплообесп. СВ, %],

    -- Общее теплообеспечение
    ROUND(
        100.0 * 
        (COALESCE([Получ. отопл. (зав.), Гкал/ч], 0) + COALESCE([Получ. отопл. (незав.), Гкал/ч], 0) + COALESCE([Получ. вент., Гкал/ч], 0))
        / NULLIF(
            COALESCE([Треб. отопл. (зав.), Гкал/ч], 0) + COALESCE([Треб. отопл. (незав.), Гкал/ч], 0) + COALESCE([Треб. вент., Гкал/ч], 0),
            0
        ),
        2
    ) AS [Теплообесп., %],

    -- Режим работы
    CASE 
        WHEN 
            (COALESCE([Получ. отопл. (зав.), Гкал/ч], 0) + COALESCE([Получ. отопл. (незав.), Гкал/ч], 0) + COALESCE([Получ. вент., Гкал/ч], 0))
            / NULLIF(
                COALESCE([Треб. отопл. (зав.), Гкал/ч], 0) + COALESCE([Треб. отопл. (незав.), Гкал/ч], 0) + COALESCE([Треб. вент., Гкал/ч], 0),
                0
            ) IS NULL 
            THEN N'Нет данных'

        WHEN 
            100.0 * (COALESCE([Получ. отопл. (зав.), Гкал/ч], 0) + COALESCE([Получ. отопл. (незав.), Гкал/ч], 0) + COALESCE([Получ. вент., Гкал/ч], 0))
            / NULLIF(
                COALESCE([Треб. отопл. (зав.), Гкал/ч], 0) + COALESCE([Треб. отопл. (незав.), Гкал/ч], 0) + COALESCE([Треб. вент., Гкал/ч], 0),
                0
            ) < 70 
            THEN N'Дефицит тепла'

        WHEN 
            100.0 * (COALESCE([Получ. отопл. (зав.), Гкал/ч], 0) + COALESCE([Получ. отопл. (незав.), Гкал/ч], 0) + COALESCE([Получ. вент., Гкал/ч], 0))
            / NULLIF(
                COALESCE([Треб. отопл. (зав.), Гкал/ч], 0) + COALESCE([Треб. отопл. (незав.), Гкал/ч], 0) + COALESCE([Треб. вент., Гкал/ч], 0),
                0
            ) > 100 
            THEN N'Перерасход тепла'

        ELSE N'Допустимо'
    END AS [Режим]

FROM SourceData

-- Показываем ТОЛЬКО проблемные обобщённые потребители (вне диапазона 70–100%)
WHERE 
    ROUND(
        100.0 * 
        (COALESCE([Получ. отопл. (зав.), Гкал/ч], 0) + COALESCE([Получ. отопл. (незав.), Гкал/ч], 0) + COALESCE([Получ. вент., Гкал/ч], 0))
        / NULLIF(
            COALESCE([Треб. отопл. (зав.), Гкал/ч], 0) + COALESCE([Треб. отопл. (незав.), Гкал/ч], 0) + COALESCE([Треб. вент., Гкал/ч], 0),
            0
        ),
        2
    ) NOT BETWEEN 70 AND 100
   OR 
    -- Или если требуемая нагрузка = 0 (на всякий случай)
    COALESCE([Треб. отопл. (зав.), Гкал/ч], 0) + COALESCE([Треб. отопл. (незав.), Гкал/ч], 0) + COALESCE([Треб. вент., Гкал/ч], 0) = 0

ORDER BY 
    [Теплообесп., %] ASC,  -- сначала самые "холодные"
    [Наименование]
